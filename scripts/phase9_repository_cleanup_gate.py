#!/usr/bin/env python3
"""Conservative Phase 9 gate: inventory and no-destructive-cleanup checks."""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
def text(rel):
    return (ROOT / rel).read_text(encoding="utf-8")
def run(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True)

tracked = run("git", "ls-files").splitlines()
status = run("git", "status", "--short")
checks = [
    ("manifest exists", (ROOT / "docs/REPOSITORY_DOCUMENT_LINEAGE.md").is_file()),
    ("reports index exists", (ROOT / "docs/REPORTS_INDEX.md").is_file()),
    ("cleanup review exists", (ROOT / "docs/audit/PHASE9_REPOSITORY_CLEANUP_REVIEW_2026-11-13.md").is_file()),
    ("tracked pyc is documented", "scripts/__pycache__/build_validation.cpython-312.pyc" in tracked and "build_validation.cpython-312.pyc" in text("docs/audit/PHASE9_REPOSITORY_CLEANUP_REVIEW_2026-11-13.md")),
    ("generated bytecode remains ignored", "__pycache__/" in text(".gitignore") and "*.py[cod]" in text(".gitignore")),
    ("no deletion staged in working tree", " D " not in status and "D  " not in status),
]
for name, ok in checks:
    print(f"{'PASS' if ok else 'FAIL'} {name}")
failed = [name for name, ok in checks if not ok]
if failed:
    raise SystemExit("Phase 9 cleanup gate failed: " + ", ".join(failed))
print(f"Phase 9 cleanup gate passed: {len(checks)}/{len(checks)}")
