package com.airi.assistant.attachments

import com.airi.assistant.workspace.ArtifactManager

/**
 * Bridges deterministic document generation to the workspace artifact store.
 * Callers can place [link] directly in an AIRI assistant message; the link is
 * an internal identifier and never contains a private filesystem path.
 */
class GeneratedArtifactService(private val artifactManager: ArtifactManager) {
    data class GeneratedArtifactLink(
        val artifactId: String,
        val fileName: String,
        val mimeType: String,
        val link: String,
        val downloadUri: String?,
    ) {
        fun markdown(): String = "[$fileName]($link)"
    }

    suspend fun generateDocument(
        sessionId: String,
        fileName: String,
        content: String,
        description: String = "Generated by AIRI",
        agentId: String = "document_generator",
    ): GeneratedArtifactLink {
        val generated = DocumentGenerator.generate(fileName, content)
        val type = when (generated.fileName.substringAfterLast('.', "").lowercase()) {
            "odt" -> ArtifactManager.ArtifactType.ODT
            "ods" -> ArtifactManager.ArtifactType.ODS
            "odp" -> ArtifactManager.ArtifactType.ODP
            "epub" -> ArtifactManager.ArtifactType.EPUB
            else -> throw IllegalArgumentException("This service is intended for packaged document outputs")
        }
        val artifact = artifactManager.createBinaryArtifact(
            sessionId = sessionId,
            name = generated.fileName,
            type = type,
            bytes = generated.bytes,
            mimeType = generated.mimeType,
            description = description,
            agentId = agentId,
        )
        return GeneratedArtifactLink(
            artifactId = artifact.id,
            fileName = generated.fileName,
            mimeType = generated.mimeType,
            link = artifactManager.internalLink(artifact.id),
            downloadUri = artifactManager.downloadUri(artifact.id)?.toString(),
        )
    }
}
