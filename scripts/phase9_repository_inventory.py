#!/usr/bin/env python3
"""Generate conservative Phase 9 repository lineage artifacts.

No file is moved or deleted. The output records provenance, duplicate hashes,
and retention decisions so cleanup can be reviewed before any destructive step.
"""
from __future__ import annotations

import hashlib
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TODAY = date.today().isoformat()
TARGET_ROOTS = (ROOT / "docs", ROOT / "reports", ROOT / "attached_assets")
REPORTS = [
    "docs/product/AIRI_PHASE8_RELEASE_READINESS.md",
    "docs/product/AIRI_PRODUCT_CAPABILITY_MATRIX.md",
    "docs/product/AIRI_RELEASE_CAPABILITY_RECORD.md",
    "docs/product/AIRI_SCHEDULE_ACCEPTANCE_MATRIX.md",
    "docs/multiplatform/DESKTOP_PHASE8_EVIDENCE.md",
    "docs/AIRI_KNOWN_LIMITATIONS.md",
    "docs/product/AIRI_RELEASE_CLOSURE.md",
    "docs/product/RELEASE_AUDIT_REGISTER.md",
    "reports/phase8-final-verification-report.md",
    "docs/audit/AIRI_EXTERNAL_GATE_MATRIX.md",
]

def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()

def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()

def git(*args: str) -> str:
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True).strip()

def last_commit(path: str) -> tuple[str, str]:
    out = git("log", "-1", "--format=%h%x09%s", "--", path)
    if not out:
        return ("uncommitted", "No commit recorded")
    return tuple(out.split("\t", 1))  # type: ignore[return-value]

files = [p for root in TARGET_ROOTS if root.exists() for p in root.rglob("*") if p.is_file()]
hashes: dict[str, list[str]] = {}
for path in files:
    hashes.setdefault(sha(path), []).append(rel(path))

duplicate_hash = {name: h for h, names in hashes.items() if len(names) > 1 for name in names}

manifest = [
    "# AIRI Repository Document Lineage Manifest",
    "",
    f"**Generated:** {TODAY}",
    "**Generated by:** `scripts/phase9_repository_inventory.py`",
    "**Policy:** inventory only; no move or deletion is performed by this generator.",
    "",
    "Fields: canonical path, last commit, source/role, generated-by, duplicate SHA-256, retention decision.",
    "",
    "| Canonical path | Last commit | Source / role | Generated-by | Duplicate SHA-256 | Retention |",
    "|---|---|---|---|---|---|",
]
for path in sorted(files, key=rel):
    name = rel(path)
    commit, subject = last_commit(name)
    suffix = path.suffix.lower()
    if name.startswith("attached_assets/"):
        role = "historical attached source or evidence asset"
        retention = "RETAIN / historical evidence; do not canonicalize without owner approval"
    elif name.startswith("reports/"):
        role = "historical or generated verification report"
        retention = "RETAIN / report lineage required"
    else:
        role = "repository documentation"
        retention = "RETAIN / canonical documentation path"
    dup = duplicate_hash.get(name, "none")
    dup_display = f"`{dup[:16]}…`" if dup != "none" else "none"
    manifest.append(f"| `{name}` | `{commit}` — {subject.replace('|', '\\|')} | {role} | `phase9_repository_inventory.py` | {dup_display} | {retention} |")
(ROOT / "docs" / "REPOSITORY_DOCUMENT_LINEAGE.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")

index = [
    "# AIRI Reports Index — Phase 9",
    "",
    f"**Generated:** {TODAY}",
    "**Generated by:** `scripts/phase9_repository_inventory.py`",
    "",
    "This is a curated navigation index, not a replacement for historical reports. Each row is resolved against Git history at generation time.",
    "",
    "| # | Report | Last commit | Commit subject | Verification / scope |",
    "|---:|---|---|---|---|",
]
for i, name in enumerate(REPORTS, 1):
    path = ROOT / name
    if path.exists():
        commit, subject = last_commit(name)
        scope = "current release evidence" if i <= 6 else "historical release/audit evidence"
        link = name.removeprefix("docs/") if name.startswith("docs/") else "../" + name
        index.append(f"| {i} | [`{name}`]({link}) | `{commit}` | {subject.replace('|', '\\|')} | {scope} |")
    else:
        index.append(f"| {i} | `{name}` | **MISSING** | — | review required |")
(ROOT / "docs" / "REPORTS_INDEX.md").write_text("\n".join(index) + "\n", encoding="utf-8")

print(f"Generated manifest for {len(files)} files")
print(f"Byte-identical groups: {sum(1 for names in hashes.values() if len(names) > 1)}")
print("Generated docs/REPOSITORY_DOCUMENT_LINEAGE.md and docs/REPORTS_INDEX.md")
