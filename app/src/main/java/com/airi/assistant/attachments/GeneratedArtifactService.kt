package com.airi.assistant.attachments

import com.airi.assistant.workspace.ArtifactManager
import com.airi.assistant.workspace.ArtifactProvenance
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.io.File
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/** Canonical AgentLoop writer: success is returned only after physical verification. */
class GeneratedArtifactService(private val artifactManager: ArtifactManager) {
    data class GeneratedArtifactLink(
        val artifactId: String, val fileName: String, val mimeType: String,
        val size: Long, val sha256: String, val link: String, val downloadUri: String?,
        val provenance: String, val runId: String? = null, val traceId: String? = null,
    ) {
        fun markdown(): String = "[$fileName]($link)"
        fun structured(): String = JSONObject().apply {
            put("artifactId", artifactId); put("fileName", fileName); put("mimeType", mimeType)
            put("size", size); put("sha256", sha256); put("provenance", provenance)
            put("runId", runId ?: JSONObject.NULL); put("traceId", traceId ?: JSONObject.NULL)
            put("preview", link); put("download", downloadUri ?: JSONObject.NULL)
            put("shareState", if (downloadUri == null) "unavailable" else "available"); put("verified", true)
        }.toString()
    }

    suspend fun generateDocument(sessionId: String, fileName: String, content: String, description: String = "Generated by AIRI", agentId: String = "document_generator", runId: String? = null, traceId: String? = null) =
        generate(sessionId, fileName, content, description, agentId, runId, traceId)

    suspend fun generateSpreadsheet(sessionId: String, fileName: String, content: String, runId: String? = null, traceId: String? = null) =
        generate(sessionId, ensureExtension(fileName, "xlsx"), content, "Generated spreadsheet", "spreadsheet_generator", runId, traceId)

    suspend fun generatePdf(sessionId: String, fileName: String, content: String, runId: String? = null, traceId: String? = null) =
        generate(sessionId, ensureExtension(fileName, "pdf"), content, "Generated PDF", "pdf_generator", runId, traceId)

    private suspend fun generate(sessionId: String, fileName: String, content: String, description: String, agentId: String, runId: String?, traceId: String?): GeneratedArtifactLink {
        val generated = DocumentGenerator.generate(fileName, content)
        val type = when (generated.fileName.substringAfterLast('.', "").lowercase()) {
            "odt" -> ArtifactManager.ArtifactType.ODT; "ods" -> ArtifactManager.ArtifactType.ODS
            "odp" -> ArtifactManager.ArtifactType.ODP; "epub" -> ArtifactManager.ArtifactType.EPUB
            "docx" -> ArtifactManager.ArtifactType.DOCX; "xlsx" -> ArtifactManager.ArtifactType.XLSX
            "pdf" -> ArtifactManager.ArtifactType.PDF
            else -> throw IllegalArgumentException("This service is intended for packaged document outputs")
        }
        return store(sessionId, generated.fileName, generated.mimeType, type, generated.bytes, description, agentId, runId, traceId)
    }

    suspend fun compressFiles(sessionId: String, artifactIds: List<String>, fileName: String = "airi-artifacts.zip", runId: String? = null, traceId: String? = null): GeneratedArtifactLink {
        require(artifactIds.isNotEmpty()) { "At least one artifact is required" }
        val bytes = ByteArrayOutputStream().use { output ->
            ZipOutputStream(output).use { zip ->
                artifactIds.distinct().forEach { id ->
                    val artifact = artifactManager.getArtifactForProject(id, sessionId) ?: throw IllegalArgumentException("Artifact is not available in this project: $id")
                    val file = File(artifact.filePath); require(file.isFile) { "Artifact file is missing: $id" }
                    zip.putNextEntry(ZipEntry(artifact.name)); file.inputStream().use { it.copyTo(zip) }; zip.closeEntry()
                }
            }
            output.toByteArray()
        }
        return store(sessionId, ensureExtension(fileName, "zip"), "application/zip", ArtifactManager.ArtifactType.ARCHIVE, bytes, "Compressed AIRI artifacts", "artifact_compressor", runId, traceId)
    }

    private suspend fun store(sessionId: String, fileName: String, mimeType: String, type: ArtifactManager.ArtifactType, bytes: ByteArray, description: String, agentId: String, runId: String?, traceId: String?): GeneratedArtifactLink {
        // ArtifactProvenance only persists durable task/run/step triples. The
        // standalone AgentLoop run/trace are returned in the structured result
        // and kept in the bounded summary until a task step is available.
        val provenance = ArtifactProvenance(projectId = sessionId, toolId = agentId, summary = "AgentLoop artifact generation; run=${runId?.take(40) ?: "none"}; trace=${traceId?.take(40) ?: "none"}")
        val artifact = artifactManager.createBinaryArtifact(sessionId, fileName, type, bytes, mimeType, description, agentId, provenance)
        check(artifactManager.verifyArtifact(artifact.id)) { "Artifact was not verified on disk" }
        return GeneratedArtifactLink(artifact.id, artifact.name, mimeType, artifact.sizeBytes, artifact.contentHash, artifactManager.internalLink(artifact.id), artifactManager.downloadUri(artifact.id)?.toString(), artifact.provenanceSummary, runId, traceId)
    }

    suspend fun updateDocument(artifactId: String, content: String): GeneratedArtifactLink {
        val existing = artifactManager.getArtifact(artifactId) ?: throw IllegalArgumentException("Artifact not found: $artifactId")
        require(existing.type in setOf(ArtifactManager.ArtifactType.DOCX, ArtifactManager.ArtifactType.XLSX, ArtifactManager.ArtifactType.ODT, ArtifactManager.ArtifactType.ODS, ArtifactManager.ArtifactType.ODP, ArtifactManager.ArtifactType.EPUB, ArtifactManager.ArtifactType.PDF))
        val generated = DocumentGenerator.generate(existing.name, content)
        val updated = artifactManager.updateBinaryArtifact(existing.id, generated.bytes) ?: throw IllegalStateException("Artifact could not be updated")
        check(artifactManager.verifyArtifact(updated.id)) { "Updated artifact was not verified on disk" }
        return GeneratedArtifactLink(updated.id, updated.name, generated.mimeType, updated.sizeBytes, updated.contentHash, artifactManager.internalLink(updated.id), artifactManager.downloadUri(updated.id)?.toString(), updated.provenanceSummary)
    }

    private fun ensureExtension(name: String, extension: String): String {
        val clean = name.trim().substringAfterLast('/').substringAfterLast('\\')
        return if (clean.substringAfterLast('.', "").equals(extension, true)) clean else "$clean.$extension"
    }
}
